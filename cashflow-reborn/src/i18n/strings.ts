export type UIKey = keyof typeof UI;

/** Translate a UI key with optional `{param}` interpolation. */
export function t(key: UIKey, lang: Lang, params?: Record<string, string | number>): string {
  const entry = UI[key];
  let s = (entry?.[lang] ?? entry?.en ?? key) as string;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
  return s;
}
